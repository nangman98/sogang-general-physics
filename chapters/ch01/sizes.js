export const log10Of = ([, mant, exp]) => exp + Math.log10(mant);
export const sourceOf = (q, row) => row[3] ?? `교재 표 ${q.table}`;

// 10^n (단위 q.unit)을 접두어로 쓴 꼴. 질량은 그램에 접두어를 붙인다(1 kg = 10³ g).
// 맞는 접두어가 없으면(계수가 1000 이상이 되거나 욕토보다 작으면) null.
export function prefixed(q, n) {
  const e = n + q.shift;
  const p = PREFIXES.find(([k]) => k <= e);
  if (!p || e - p[0] >= 3) return null;
  return { coef: 10 ** (e - p[0]), symbol: p[1] + q.base, reading: p[2] + q.baseKo };
}

export function nearest(q, n) {
  return q.items.reduce((a, b) => (Math.abs(log10Of(b) - n) < Math.abs(log10Of(a) - n) ? b : a));
}
